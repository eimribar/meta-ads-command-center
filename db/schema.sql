-- Tables for Meta Ads Command Center. Safe to run more than once: nothing is dropped or overwritten.
-- Run it with `npm run db:setup`, or paste it into your Postgres SQL console.

-- The brain: business facts, policy and preferences the team writes from Slack.
create table if not exists brain (
  scope       text not null,
  key         text not null,
  content     jsonb,
  updated_by  text,
  updated_at  timestamptz not null default now(),
  primary key (scope, key)
);

create table if not exists brain_history (
  id          bigint generated by default as identity primary key,
  scope       text not null,
  key         text not null,
  content     jsonb,
  action      text not null,               -- set | rm
  changed_by  text,
  changed_at  timestamptz not null default now()
);

-- Chat memory per Slack thread or DM.
create table if not exists conversations (
  convo_key   text primary key,
  messages    jsonb not null default '[]',
  updated_at  timestamptz not null default now()
);

-- Every optimizer proposal, approval, rejection and undo.
create table if not exists actions_log (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  run_date         date not null,
  cadence          text,
  action_type      text not null,
  target_level     text,
  target_id        text not null,
  target_name      text,
  before           jsonb,
  after            jsonb,
  reason           text,
  explain          text,
  guardrail_checks jsonb,
  autonomy_level   text,
  disposition      text not null,          -- proposed | escalated | auto_applied | applied_by_human | unknown | skipped
  applied          boolean not null default false,
  applied_at       timestamptz,
  applied_by       text,
  escalated        boolean not null default false,
  close_reason     text,                   -- human_reject | execution_needs_review | moot | expiry | duplicate | undone
  fail_key         text,
  decision_note    text,
  decision_key     text,
  evidence         jsonb,
  card_ts          text,
  card_channel     text,
  undone_at        timestamptz,
  undone_by        text,
  journal_id       bigint                  -- the write_journal row of the Meta write, once sent
);
create index if not exists actions_log_open on actions_log (disposition);
create index if not exists actions_log_key on actions_log (decision_key);
-- Added after the first release; an upgrade adds them. Each runs only when it is missing, so
-- running this file again needs no more than the right to use the tables.
do $$ begin
  if not exists (select 1 from information_schema.columns
                 where table_schema = current_schema() and table_name = 'actions_log' and column_name = 'journal_id') then
    alter table actions_log add column journal_id bigint;
  end if;
end $$;
-- One open card per move. Older duplicate open cards are closed before the index is made.
do $$ begin
  if not exists (select 1 from pg_indexes where schemaname = current_schema() and indexname = 'actions_log_one_open') then
    update actions_log a set disposition = 'skipped', close_reason = 'duplicate', applied_by = 'upgrade',
        decision_note = 'closed: a newer card for the same move is open'
      where a.disposition in ('proposed', 'escalated') and a.decision_key is not null
        and exists (select 1 from actions_log b where b.decision_key = a.decision_key
                    and b.disposition in ('proposed', 'escalated') and b.id > a.id);
    create unique index actions_log_one_open on actions_log (decision_key)
      where disposition in ('proposed', 'escalated');
  end if;
end $$;

-- The autonomy ladder: every action type starts on propose.
create table if not exists autonomy_policy (
  action_type text primary key,
  mode        text not null default 'propose' check (mode in ('propose', 'auto')),
  updated_at  timestamptz not null default now(),
  updated_by  text
);
insert into autonomy_policy (action_type, mode, updated_by) values
  ('pause_ad', 'propose', 'install'),
  ('unpause_ad', 'propose', 'install'),
  ('scale_budget', 'propose', 'install'),
  ('descale_budget', 'propose', 'install')
on conflict (action_type) do nothing;

-- Daily numbers pulled from Meta, per ad, ad set and campaign.
create table if not exists performance_daily (
  date          date not null,
  level         text not null,             -- ad | adset | campaign
  entity_id     text not null,
  name          text,
  campaign_id   text,
  adset_id      text,
  status        text,
  daily_budget  numeric(14,2),
  spend         numeric(14,2) not null default 0,
  impressions   bigint not null default 0,
  clicks        bigint not null default 0,
  results       numeric(14,2) not null default 0,
  secondary     numeric(14,2) not null default 0,
  pulled_at     timestamptz not null default now(),
  primary key (date, level, entity_id)
);

-- Lessons distilled from the team's approve and reject notes.
create table if not exists learnings (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  lesson      text not null,
  source      text,
  active      boolean not null default true
);

-- A plain event log: budget changes, orders, pauses.
create table if not exists timeline (
  id      bigint generated by default as identity primary key,
  at      timestamptz not null default now(),
  event   text not null,
  detail  jsonb
);

-- One row per scheduled job and time slot, so no job runs or posts twice.
create table if not exists job_runs (
  name         text not null,
  slot         text not null,
  status       text not null,              -- running | ok | held | failed
  started_at   timestamptz not null default now(),
  finished_at  timestamptz,
  summary      text,
  error        text,
  primary key (name, slot)
);

-- Last success and failure of each loop.
create table if not exists loop_health (
  loop                  text primary key,
  last_ok_at            timestamptz,
  last_error_at         timestamptz,
  last_error            text,
  consecutive_failures  integer not null default 0,
  updated_at            timestamptz not null default now()
);

-- Every write to Meta, recorded before it is sent.
create table if not exists write_journal (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  write_key    text not null unique,
  source       jsonb,
  operations   jsonb not null,
  metadata     jsonb,
  state        text not null,              -- claimed | dispatching | applied | not_applied | unknown | reconciled
  receipt      jsonb,
  updated_at   timestamptz not null default now()
);

-- Problems worth a human's attention, opened and resolved by the agent.
create table if not exists incidents (
  key           text primary key,
  severity      text not null default 'warn',
  text          text not null,
  opened_at     timestamptz not null default now(),
  last_seen_at  timestamptz not null default now(),
  resolved_at   timestamptz
);

-- Small key/value state: the daily desk message, the freeze state, repeat-post guards.
create table if not exists state (
  key         text primary key,
  value       jsonb,
  updated_at  timestamptz not null default now()
);

-- Every comment the moderation sweep acted on or flagged.
create table if not exists moderation_log (
  id          bigint generated by default as identity primary key,
  at          timestamptz not null default now(),
  platform    text not null,
  comment_id  text not null,
  surface     text,
  author      text,
  text        text,
  category    text,
  confidence  numeric(4,3),
  action      text not null,               -- hide | delete | flag | reply | unhide
  outcome     text,
  source      text,
  unique (platform, comment_id, action)
);

-- Decisions the team made, each with its reason. The agent reads the active ones every turn, so
-- it never proposes again what the team already decided against. Approvals and rejections of the
-- agent's own cards stay in actions_log; this table is for everything else.
create table if not exists decisions (
  id          bigint generated by default as identity primary key,
  decided_at  timestamptz not null default now(),
  topic       text,
  decision    text not null,
  why         text not null,
  decided_by  text,
  source      text,
  replaces    bigint,                      -- the decision this one overrides
  brain_key   text,                        -- the brain row it set, as section/name, if any
  status      text not null default 'active' check (status in ('active', 'replaced', 'reversed')),
  closed_at   timestamptz,
  closed_by   text,
  close_note  text
);
create index if not exists decisions_status on decisions (status);

-- What the team believes works, or is testing, graded against the results later.
-- labels holds any segment the claim is about, like {"audience":"commuters","angle":"theft"}.
create table if not exists hypotheses (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  created_by  text,
  claim       text not null,
  kind        text not null default 'hypothesis' check (kind in ('hypothesis', 'test')),
  labels      jsonb not null default '{}',
  started     date,
  ended       date,
  evidence    jsonb,
  verdict     text not null default 'pending' check (verdict in ('pending', 'confirmed', 'refuted')),
  graded_at   timestamptz,
  graded_by   text,
  grade_note  text
);
create index if not exists hypotheses_verdict on hypotheses (verdict);
